/**
 * Generates prisma/schema.postgres.prisma from prisma/schema.prisma.
 *
 * Why: local dev + tests stay on SQLite (zero-friction, jest global-setup
 * recreates it), while production runs Supabase Postgres. schema.prisma is
 * the single source of truth for MODELS; this script copies it verbatim and
 * swaps ONLY the datasource block to Postgres (+ directUrl for migrations).
 *
 * The committed output is drift-checked byte-for-byte by
 * tests/schema-sync.test.ts — if you edit schema.prisma, re-run:
 *
 *   node scripts/sync-postgres-schema.mjs     (or: bun scripts/sync-postgres-schema.mjs)
 *
 * and commit the regenerated file together with schema.prisma.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PRISMA_DIR = join(HERE, '..', 'prisma');
const SOURCE = join(PRISMA_DIR, 'schema.prisma');
const TARGET = join(PRISMA_DIR, 'schema.postgres.prisma');

/** First line of the generated file — loudly says "do not hand-edit". */
export const GENERATED_HEADER =
  '// GENERATED by scripts/sync-postgres-schema.mjs — do not hand-edit; models live in schema.prisma';

const DATASOURCE_RE = /datasource\s+\w+\s*\{[^}]*\}/;
const PROVIDER_RE = /provider\s*=\s*"[^"]*"/;
const URL_RE = /url\s*=\s*env\(\s*"DATABASE_URL"\s*\)/;

/**
 * Pure string transform: SQLite schema source → Postgres schema source.
 * Fails loudly (never silently no-ops) when the datasource block's shape
 * changes in a way this transform cannot handle.
 */
export function toPostgresSchema(sqliteSource) {
  const match = sqliteSource.match(DATASOURCE_RE);
  if (!match) {
    throw new Error('datasource block not found in schema.prisma — update sync-postgres-schema.mjs');
  }
  if (match.index > 0 && DATASOURCE_RE.test(sqliteSource.slice(match.index + 1))) {
    throw new Error('multiple datasource blocks found — update sync-postgres-schema.mjs');
  }

  const sqliteBlock = match[0];

  const providerSwapped = sqliteBlock.replace(PROVIDER_RE, 'provider = "postgresql"');
  if (providerSwapped === sqliteBlock) {
    throw new Error('provider line not found in datasource block — update sync-postgres-schema.mjs');
  }

  const withDirectUrl = providerSwapped.replace(
    URL_RE,
    (urlLine) => `${urlLine}\n  directUrl = env("DIRECT_URL")`,
  );
  if (withDirectUrl === providerSwapped) {
    throw new Error('url env("DATABASE_URL") line not found in datasource block — update sync-postgres-schema.mjs');
  }

  return `${GENERATED_HEADER}\n\n${sqliteSource.replace(DATASOURCE_RE, withDirectUrl)}`;
}

const isDirectRun =
  typeof process !== 'undefined' &&
  Boolean(process.argv[1]) &&
  import.meta.url === pathToFileURL(process.argv[1]).href;

if (isDirectRun) {
  const source = readFileSync(SOURCE, 'utf8');
  const generated = toPostgresSchema(source);
  writeFileSync(TARGET, generated, 'utf8');
  console.log(`wrote ${TARGET}`);
  console.log('  provider: sqlite → postgresql, + directUrl = env("DIRECT_URL"); models untouched');
}
